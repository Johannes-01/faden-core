import Foundation

/// The block-quote header placed under the title of each notes file.
public struct NotesHeader: Sendable {
    public var date: Date
    public var style: String
    public var slides: [String]
    public var audio: [String]
    public var userNotes: String?
    public var notesCall: PaidCall
    /// nil when verification was skipped before a call was made.
    public var verifyCall: PaidCall?
    public var verification: String

    public init(date: Date, style: String, slides: [String], audio: [String], userNotes: String?,
                notesCall: PaidCall, verifyCall: PaidCall?, verification: String) {
        self.date = date
        self.style = style
        self.slides = slides
        self.audio = audio
        self.userNotes = userNotes
        self.notesCall = notesCall
        self.verifyCall = verifyCall
        self.verification = verification
    }

    public func markdown() -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.calendar = Calendar(identifier: .gregorian)
        formatter.timeZone = .current
        formatter.dateFormat = "yyyy-MM-dd"

        func list(_ items: [String]) -> String { items.isEmpty ? "none" : items.joined(separator: ", ") }

        let calls = [notesCall] + (verifyCall.map { [$0] } ?? [])
        let usages = calls.map(\.usage)
        let tokensIn = usages.reduce(0) { $0 + $1.inputTokens + $1.cacheReadInputTokens + $1.cacheCreationInputTokens }
        let tokensOut = usages.reduce(0) { $0 + $1.outputTokens }
        // An unpriced call shows as unknown, never as $0.
        let unpriced = calls.filter { $0.usd == nil }.map(\.model)
        let cost = unpriced.isEmpty
            ? String(format: "$%.2f", calls.compactMap(\.usd).reduce(0, +))
            : "— (price unknown for \(unpriced.joined(separator: ", ")))"
        let checkModel = verifyCall?.model ?? Verifier.model

        return [
            "> Generated by Faden on \(formatter.string(from: date)) · style \(style) · notes: \(notesCall.model) · check: \(checkModel)",
            "> Sources: slides \(list(slides)) · audio \(list(audio)) · my notes \(userNotes ?? "none")",
            "> Labels: 📄 slides · 🗣 lecture · 💡 model addition · ✍️ my notes · ⚠️ not found in sources",
            "> Verification: \(verification)",
            "> Cost: \(cost) (\(tokensIn) in / \(tokensOut) out tokens)",
            "",
            "",
        ].joined(separator: "\n")
    }

    /// Places the header after a leading `# Title` line, or at the very top if there is none.
    public func insert(into notes: String) -> String {
        if notes.hasPrefix("# ") {
            let title: Substring
            let rest: Substring
            if let nl = notes.firstIndex(of: "\n") {
                title = notes[..<nl]
                rest = notes[notes.index(after: nl)...]
            } else {
                title = notes[...]
                rest = ""
            }
            return "\(title)\n\n\(markdown())\(rest)"
        }
        return markdown() + notes
    }
}
