import Foundation

public enum StudyGuideError: Error, Equatable {
    /// No lecture with notes was chosen.
    case noLectures
    /// The notes together are more than one call takes; carries their size in characters.
    case tooLarge(Int)
}

/// A study guide for a course (#27): one call over the chosen lectures' notes, written to
/// `Study guide <date>.md` in the course folder, with links into each lecture's notes.
public enum StudyGuide {
    /// One lecture the guide is made from.
    public struct Lecture: Equatable, Sendable {
        public var title: String
        /// The lecture folder, relative to the course folder (e.g. `Block 1/2026-10-28 Session 4`), which the
        /// guide's links name.
        public var path: String
        /// The notes file's Markdown.
        public var notes: String

        public init(title: String, path: String, notes: String) {
            self.title = title
            self.path = path
            self.notes = notes
        }
    }

    /// About 150k tokens of notes: what one call takes with room for the answer.
    public static let maxCharacters = 500_000

    public static func request(_ lectures: [Lecture], model: String = NotesPrompt.model) throws -> MessageRequest {
        guard !lectures.isEmpty else { throw StudyGuideError.noLectures }
        let text = lectures.enumerated().map { i, lecture in
            "=== Lecture L\(i + 1): \(lecture.title) ===\n\n" + StudyText.withoutHeader(lecture.notes)
                .trimmingCharacters(in: .whitespacesAndNewlines)
        }.joined(separator: "\n\n")
        guard text.count <= maxCharacters else { throw StudyGuideError.tooLarge(text.count) }
        return try template(model: model, messages: [Message(content: [.text(text, cache: false)])])
    }

    /// Everything but the content; shared with the hosted mode (`HostedRequest`).
    static func template(model: String, messages: [Message]) throws -> MessageRequest {
        MessageRequest(
            model: model,
            maxTokens: 32000,
            stream: true,
            system: [.text(try StudyText.prompt("study-guide-system"), cache: false)],
            messages: messages,
            outputConfig: OutputConfig(effort: "high"),
            tag: RequestTag(step: .studyGuide))
    }

    /// The model's guide with its `lecture:L<n>#<heading>` links pointing at the lectures' notes
    /// (`faden:lecture?path=…&heading=…`), a Faden header under the title, and the lectures it was made from.
    public static func markdown(_ reply: String, lectures: [Lecture], call: PaidCall, date: Date) -> String {
        var guide = reply.trimmingCharacters(in: .whitespacesAndNewlines)
        // A heading may hold parentheses of its own, e.g. `Abbruch (prüfungsrelevant)`.
        let link = /\]\(lecture:L(\d+)(?:#((?:[^()\n]|\([^()\n]*\))*))?\)/
        guide = guide.replacing(link) { match in
            // A link to a lecture the guide doesn't have would go nowhere; its text stays.
            guard let n = Int(match.1), lectures.indices.contains(n - 1) else { return "]" }
            let heading = match.2.map { String($0).removingPercentEncoding ?? String($0) }
            return "](" + lectureLink(path: lectures[n - 1].path, heading: heading) + ")"
        }

        let sources = lectures.enumerated().map { i, lecture in
            "[L\(i + 1) \(lecture.title)](\(lectureLink(path: lecture.path, heading: nil)))"
        }
        let header = [
            "> Generated by [Faden](\(NotesHeader.websiteURL)) on \(StudyText.day(date)) · study guide from "
                + "\(lectures.count == 1 ? "1 lecture" : "\(lectures.count) lectures") · model: \(call.model)",
            "> Lectures: " + sources.joined(separator: " · "),
            "> Cost: \(NotesHeader.cost(of: [call]))",
        ].joined(separator: "\n")
        var lines = guide.components(separatedBy: "\n")
        if lines.first?.hasPrefix("# ") == true {
            lines.insert(contentsOf: ["", header], at: 1)
        } else {
            lines.insert(contentsOf: [header, ""], at: 0)
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// `faden:lecture?path=<relative folder>&heading=<heading>`, which the app opens as that lecture's notes.
    public static func lectureLink(path: String, heading: String?) -> String {
        var components = URLComponents()
        components.scheme = "faden"
        components.path = "lecture"
        components.queryItems = [URLQueryItem(name: "path", value: path)]
            + (heading.map { [URLQueryItem(name: "heading", value: $0)] } ?? [])
        // `(` and `)` would end the Markdown link early.
        return components.url!.absoluteString
            .replacingOccurrences(of: "(", with: "%28").replacingOccurrences(of: ")", with: "%29")
    }

    /// `Study guide 2026-11-02.md`, or `Study guide 2026-11-02 2.md` when that exists.
    public static func fileURL(in course: URL, date: Date) -> URL {
        let base = "Study guide \(StudyText.day(date))"
        var url = course.appendingPathComponent(base + ".md")
        var n = 2
        while FileManager.default.fileExists(atPath: url.path) {
            url = course.appendingPathComponent("\(base) \(n).md")
            n += 1
        }
        return url
    }
}
