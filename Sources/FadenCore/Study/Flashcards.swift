import Foundation

/// One exam-style question from a lecture's notes, with its answer and the source label the answer rests on.
public struct Flashcard: Codable, Equatable, Sendable {
    public var question: String
    public var answer: String
    /// Copied from the notes, e.g. `🗣 [00:23:14]` or `📄 Folie 12`; empty when the model gave none.
    public var source: String

    public init(question: String, answer: String, source: String) {
        self.question = question
        self.answer = answer
        self.source = source
    }
}

public enum FlashcardsError: Error, Equatable {
    case missingResource(String)
    /// The notes have no statements to ask about.
    case emptyNotes
    /// The model's answer had no cards.
    case noCards
}

/// Turns a lecture's notes into flashcards (#26): one call over the notes, not the transcript, written to
/// `flashcards.md` in the lecture folder, readable back for a quiz and exportable for Anki.
public enum Flashcards {
    public static let fileName = "flashcards.md"

    /// The request for `notes` (the notes file's Markdown). `examples` are past exam questions of the course
    /// whose style the cards should follow.
    public static func request(notes: String, examples: String? = nil, model: String = NotesPrompt.model) throws
        -> MessageRequest {
        let body = StudyText.withoutHeader(notes)
        // Headings alone give nothing to ask about.
        let statements = body.components(separatedBy: .newlines).map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty && !$0.hasPrefix("#") }
        guard !statements.isEmpty else { throw FlashcardsError.emptyNotes }
        var content: [ContentBlock] = []
        if let examples = examples?.trimmingCharacters(in: .whitespacesAndNewlines), !examples.isEmpty {
            content.append(.text("Example questions from past exams of this course (copy their style, not their content):\n\n"
                                 + examples, cache: false))
        }
        content.append(.text("The lecture notes:\n\n" + body, cache: false))
        return MessageRequest(
            model: model,
            maxTokens: 16000,
            stream: false,
            system: [.text(try StudyText.prompt("flashcards-system"), cache: false)],
            messages: [Message(content: content)],
            outputConfig: OutputConfig(effort: "medium", format: JSONSchemaFormat(schema: schema)))
    }

    public static func parse(_ text: String) throws -> [Flashcard] {
        struct Answer: Decodable { let cards: [Flashcard] }
        let cards = try JSONDecoder().decode(Answer.self, from: Data(StudyText.json(in: text).utf8)).cards
            .map { Flashcard(question: $0.question.trimmingCharacters(in: .whitespacesAndNewlines),
                             answer: $0.answer.trimmingCharacters(in: .whitespacesAndNewlines),
                             source: $0.source.trimmingCharacters(in: .whitespacesAndNewlines)) }
            .filter { !$0.question.isEmpty && !$0.answer.isEmpty }
        guard !cards.isEmpty else { throw FlashcardsError.noCards }
        return cards
    }

    /// `flashcards.md`: the title, a Faden header, then each card as `## n. question` with the answer and its
    /// source label below, so the notes viewer shows the labels as links.
    public static func markdown(_ cards: [Flashcard], title: String, notesFile: String, call: PaidCall, date: Date)
        -> String {
        var lines = [
            "# Flashcards: \(title)", "",
            "> Generated by [Faden](\(NotesHeader.websiteURL)) on \(StudyText.day(date)) · flashcards from \(notesFile) · model: \(call.model)",
            "> Cost: \(NotesHeader.cost(of: [call]))", "",
        ]
        for (i, card) in cards.enumerated() {
            lines += ["## \(i + 1). \(StudyText.oneLine(card.question))", "",
                      card.source.isEmpty ? card.answer : "\(card.answer) \(card.source)", ""]
        }
        return lines.joined(separator: "\n")
    }

    /// The cards of a `flashcards.md`, for a quiz; the source label stays at the end of the answer.
    public static func read(_ markdown: String) -> [Flashcard] {
        var cards: [Flashcard] = []
        var question: String?
        var answer: [String] = []
        func finish() {
            guard let question else { return }
            let text = answer.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
            let (body, source) = StudyText.splitLabel(text)
            cards.append(Flashcard(question: question, answer: body, source: source))
        }
        for line in markdown.components(separatedBy: .newlines) {
            if line.hasPrefix("## ") {
                finish()
                let heading = line.dropFirst(3)
                // `## 12. Question`: the number is the card's, not part of the question.
                let number = heading.prefix { $0.isNumber }
                question = number.isEmpty || !heading.dropFirst(number.count).hasPrefix(". ")
                    ? String(heading) : String(heading.dropFirst(number.count + 2))
                answer = []
            } else if question != nil {
                answer.append(line)
            }
        }
        finish()
        return cards
    }

    /// For Anki's text import: `Front,Back,Tags` rows (RFC 4180 quoting), the source label at the end of Back,
    /// tags made of the course and lecture names.
    public static func csv(_ cards: [Flashcard], tags: [String]) -> String {
        func field(_ text: String) -> String {
            guard text.contains(where: { $0 == "," || $0 == "\"" || $0.isNewline }) else { return text }
            return "\"" + text.replacingOccurrences(of: "\"", with: "\"\"") + "\""
        }
        let tagText = tags.map { $0.split(whereSeparator: \.isWhitespace).joined(separator: "_") }
            .filter { !$0.isEmpty }.joined(separator: " ")
        let rows = cards.map { card in
            [card.question, card.source.isEmpty ? card.answer : "\(card.answer) \(card.source)", tagText]
                .map(field).joined(separator: ",")
        }
        return (["Front,Back,Tags"] + rows).joined(separator: "\r\n") + "\r\n"
    }

    private static let schema: JSONValue = .object([
        "type": .string("object"),
        "properties": .object([
            "cards": .object([
                "type": .string("array"),
                "items": .object([
                    "type": .string("object"),
                    "properties": .object([
                        "question": .object(["type": .string("string")]),
                        "answer": .object(["type": .string("string")]),
                        "source": .object(["type": .string("string")]),
                    ]),
                    "required": .array([.string("question"), .string("answer"), .string("source")]),
                    "additionalProperties": .bool(false),
                ]),
            ]),
        ]),
        "required": .array([.string("cards")]),
        "additionalProperties": .bool(false),
    ])
}

/// Helpers the study tools share.
enum StudyText {
    static func prompt(_ name: String) throws -> String {
        guard let url = FadenCore.resources.url(forResource: name, withExtension: "md", subdirectory: "prompts") else {
            throw FlashcardsError.missingResource("prompts/\(name).md")
        }
        return try String(contentsOf: url, encoding: .utf8).trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// The notes without their `> …` Faden header under the title: it names files, models and costs.
    static func withoutHeader(_ notes: String) -> String {
        var lines = notes.components(separatedBy: .newlines)
        guard let start = lines.firstIndex(where: { line in NotesHeader.firstLinePrefixes.contains { line.hasPrefix($0) } })
        else { return notes }
        var end = start
        while end < lines.count, lines[end].hasPrefix(">") { end += 1 }
        lines.removeSubrange(start..<end)
        return lines.joined(separator: "\n")
    }

    /// The JSON object in a reply, without a code fence around it.
    static func json(in text: String) -> String {
        guard let open = text.firstIndex(of: "{"), let close = text.lastIndex(of: "}"), open < close else { return text }
        return String(text[open...close])
    }

    static func oneLine(_ text: String) -> String {
        text.split(whereSeparator: \.isNewline).joined(separator: " ")
    }

    /// `text` and the source label at its end (`🗣 [..]`, `📄 …`, `✍️`, `💡`), if there is one.
    static func splitLabel(_ text: String) -> (String, String) {
        let labels = ["🗣", "📄", "✍️", "✍", "💡"]
        guard let index = labels.compactMap({ text.range(of: " " + $0, options: .backwards)?.lowerBound }).max()
        else { return (text, "") }
        let label = text[text.index(after: index)...]
        // Only a short tail is a label; a 📄 in the middle of an answer isn't.
        guard label.count <= 60, !label.contains("\n") else { return (text, "") }
        return (String(text[..<index]), String(label))
    }

    static func day(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.calendar = Calendar(identifier: .gregorian)
        formatter.timeZone = .current
        formatter.dateFormat = "yyyy-MM-dd"
        return formatter.string(from: date)
    }
}
