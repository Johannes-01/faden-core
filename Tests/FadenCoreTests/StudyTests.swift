import Foundation
import Testing
@testable import FadenCore

private let notes = """
# Raft

> Generated by [Faden](https://johannes-01.github.io/Faden-website/) on 2026-10-29 · style C · notes: claude-opus-5-5 · check: claude-haiku-5-5
> Cost: $0.82 (100 in / 10 out tokens)

## Log Matching

- Gleiche Präfixe. 🗣 [00:23:14]
"""

private let call = PaidCall(model: "claude-opus-5-5", usage: Usage(inputTokens: 1000, outputTokens: 500))
private let day = Date(timeIntervalSince1970: 1_793_620_800) // 2026-11-02

private func body(_ r: MessageRequest) throws -> [String: Any] {
    try JSONSerialization.jsonObject(with: JSONEncoder().encode(r)) as! [String: Any]
}

private func texts(_ r: MessageRequest) throws -> [String] {
    let messages = try body(r)["messages"] as! [[String: Any]]
    return (messages[0]["content"] as! [[String: Any]]).compactMap { $0["text"] as? String }
}

@Suite struct FlashcardsTests {
    @Test func theRequestSendsTheNotesWithoutTheirHeaderAndAsksForCards() throws {
        let r = try Flashcards.request(notes: notes, examples: "Was ist Raft?")
        let parts = try texts(r)
        #expect(parts.count == 2)
        #expect(parts[0].contains("Was ist Raft?"))
        #expect(parts[1].contains("Gleiche Präfixe. 🗣 [00:23:14]"))
        #expect(!parts[1].contains("Generated by") && !parts[1].contains("$0.82"))
        let json = try body(r)
        #expect(json["model"] as? String == NotesPrompt.model)
        let format = (json["output_config"] as? [String: Any])?["format"] as? [String: Any]
        #expect(((format?["schema"] as? [String: Any])?["required"] as? [String]) == ["cards"])
        #expect(throws: FlashcardsError.emptyNotes) { try Flashcards.request(notes: "# T\n\n> Generated by Faden on x\n") }
    }

    @Test func cardsRoundTripThroughTheFileAndExportForAnki() throws {
        let cards = try Flashcards.parse(#"{"cards":[{"question":"Was garantiert Log Matching?","answer":"Gleiche Präfixe, also \"dieselben\" Einträge.","source":"🗣 [00:23:14]"},{"question":" ","answer":"x","source":""},{"question":"Zweizeilig\nFrage?","answer":"Antwort","source":"📄 Folie 3"}]}"#)
        #expect(cards.count == 2)
        let file = Flashcards.markdown(cards, title: "Raft", notesFile: "notes.md", call: call, date: day)
        #expect(file.hasPrefix("# Flashcards: Raft\n\n> Generated by [Faden](https://johannes-01.github.io/Faden-website/) on 2026-11-02 · flashcards from notes.md · model: claude-opus-5-5\n> Cost: $0.01 (1000 in / 500 out tokens)\n"))
        #expect(file.contains("## 2. Zweizeilig Frage?\n\nAntwort 📄 Folie 3\n"))
        let back = Flashcards.read(file)
        #expect(back == [Flashcard(question: "Was garantiert Log Matching?", answer: "Gleiche Präfixe, also \"dieselben\" Einträge.", source: "🗣 [00:23:14]"),
                         Flashcard(question: "Zweizeilig Frage?", answer: "Antwort", source: "📄 Folie 3")])
        let csv = Flashcards.csv(back, tags: ["Security of Modern Networks", "Raft"])
        #expect(csv == "Front,Back,Tags\r\nWas garantiert Log Matching?,\"Gleiche Präfixe, also \"\"dieselben\"\" Einträge. 🗣 [00:23:14]\",Security_of_Modern_Networks Raft\r\nZweizeilig Frage?,Antwort 📄 Folie 3,Security_of_Modern_Networks Raft\r\n")
    }

    @Test func aReplyWithoutCardsIsAnError() {
        #expect(throws: FlashcardsError.noCards) { try Flashcards.parse(#"{"cards":[]}"#) }
        #expect(throws: (any Error).self) { try Flashcards.parse("not json") }
    }

    @Test func aLabelInTheMiddleOfAnAnswerStaysThere() {
        let (text, label) = StudyText.splitLabel("Siehe 📄 Folie 3 und mehr Text, der danach noch lange weitergeht und weitergeht und weitergeht.")
        #expect(label.isEmpty && text.hasPrefix("Siehe"))
        #expect(StudyText.splitLabel("Antwort ✍️") == ("Antwort", "✍️"))
    }

    @Test func bothHeaderFormsAreLeftOut() {
        let old = "# T\n\n> Generated by Faden on 2026-10-01 · style C\n> Cost: $1\n\n- a 🗣 [00:00:01]\n"
        #expect(StudyText.withoutHeader(old) == "# T\n\n\n- a 🗣 [00:00:01]\n")
        #expect(!StudyText.withoutHeader(notes).contains("Generated by"))
    }
}

@Suite struct StudyGuideTests {
    let lectures = [
        StudyGuide.Lecture(title: "Raft", path: "Block 1/2026-10-28 Raft", notes: notes),
        StudyGuide.Lecture(title: "Paxos", path: "2026-11-01 Paxos", notes: "# Paxos\n\n## Phasen\n\n- Zwei Phasen. 📄 Folie 2\n"),
    ]

    @Test func theRequestNumbersTheLectures() throws {
        let text = try texts(try StudyGuide.request(lectures))[0]
        #expect(text.hasPrefix("=== Lecture L1: Raft ===\n\n# Raft\n"))
        #expect(text.contains("=== Lecture L2: Paxos ===\n\n# Paxos"))
        #expect(!text.contains("Generated by"))
        #expect(throws: StudyGuideError.noLectures) { try StudyGuide.request([]) }
        let big = StudyGuide.Lecture(title: "x", path: "x", notes: String(repeating: "a", count: StudyGuide.maxCharacters + 1))
        do {
            _ = try StudyGuide.request([big])
            Issue.record("expected tooLarge")
        } catch StudyGuideError.tooLarge(let size) {
            #expect(size > StudyGuide.maxCharacters)
        }
    }

    @Test func linksPointAtTheLecturesNotesAndTheHeaderListsThem() {
        let reply = """
        # Verteilte Konsensverfahren

        ## Überblick

        - Log Matching sichert Präfixe. [L1](lecture:L1#Log Matching)
        - Abbruch [L2](lecture:L2#Abbruch (prüfungsrelevant)) und [L2](lecture:L2) und [L9](lecture:L9#X).
        """
        let guide = StudyGuide.markdown(reply, lectures: lectures, call: call, date: day)
        let lines = guide.components(separatedBy: "\n")
        #expect(lines[0] == "# Verteilte Konsensverfahren")
        #expect(lines[2].hasPrefix("> Generated by [Faden](https://johannes-01.github.io/Faden-website/) on 2026-11-02 · study guide from 2 lectures"))
        #expect(lines[3] == "> Lectures: [L1 Raft](faden:lecture?path=Block%201/2026-10-28%20Raft) · [L2 Paxos](faden:lecture?path=2026-11-01%20Paxos)")
        #expect(guide.contains("[L1](faden:lecture?path=Block%201/2026-10-28%20Raft&heading=Log%20Matching)"))
        #expect(guide.contains("[L2](faden:lecture?path=2026-11-01%20Paxos&heading=Abbruch%20%28pr%C3%BCfungsrelevant%29)"))
        #expect(guide.contains("und [L2](faden:lecture?path=2026-11-01%20Paxos) und [L9]."))
    }

    @Test func aGuideFileNeverReplacesAnother() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("faden-guide-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let first = StudyGuide.fileURL(in: dir, date: day)
        #expect(first.lastPathComponent == "Study guide 2026-11-02.md")
        try Data().write(to: first)
        #expect(StudyGuide.fileURL(in: dir, date: day).lastPathComponent == "Study guide 2026-11-02 2.md")
    }
}

@Suite struct StudyMakerTests {
    @Test func flashcardsAreWrittenAndBilledAsTheirOwnStep() async throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("faden-study-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: dir) }
        let folder = try LectureFolder.create(in: dir.appendingPathComponent("Course"), date: day, title: "Raft")
        let notesURL = folder.url.appendingPathComponent("notes.md")
        try notes.write(to: notesURL, atomically: true, encoding: .utf8)
        let ledger = CostLedger(file: dir.appendingPathComponent("costs.jsonl"))
        let reply = MessageResult(text: #"{"cards":[{"question":"Q?","answer":"A.","source":"🗣 [00:23:14]"}]}"#,
                                  model: "claude-sonnet-5-5", stopReason: "end_turn", usage: Usage(inputTokens: 900, outputTokens: 300))
        let client = FakeClient([.success(reply)])
        let maker = StudyMaker(client: client, ledger: ledger, model: "claude-sonnet-5-5", now: { day })

        let file = try await maker.flashcards(for: folder, notes: notesURL, title: "Raft")

        #expect(file.lastPathComponent == "flashcards.md")
        #expect(Flashcards.read(try String(contentsOf: file, encoding: .utf8)).map(\.question) == ["Q?"])
        #expect(await client.models == ["claude-sonnet-5-5"])
        let line = try String(contentsOf: ledger.file, encoding: .utf8)
        #expect(line.contains(#""step":"flashcards""#))
    }

    @Test func aGuideCutOffAtTheLimitIsNotSaved() async throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("faden-study-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let reply = MessageResult(text: "# Half", model: "claude-opus-5-5", stopReason: "max_tokens", usage: Usage())
        let maker = StudyMaker(client: FakeClient([.success(reply)]), ledger: CostLedger(file: dir.appendingPathComponent("c.jsonl")),
                               now: { day })
        await #expect(throws: AnthropicError.truncated) {
            try await maker.studyGuide(for: dir, lectures: [StudyGuide.Lecture(title: "R", path: "R", notes: notes)])
        }
        #expect(try FileManager.default.contentsOfDirectory(atPath: dir.path).filter { $0.hasPrefix("Study guide") }.isEmpty)
    }
}
