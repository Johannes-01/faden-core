import Foundation
import Testing
@testable import FadenCore

@Suite struct NotesHeaderTests {
    private func header(userNotes: String? = nil, notesModel: String = "claude-opus-5-5",
                        verify: PaidCall? = nil) -> NotesHeader {
        NotesHeader(
            date: Date(timeIntervalSince1970: 1_760_000_000),
            style: "A",
            slides: ["a.pdf", "b.pdf"],
            audio: [],
            userNotes: userNotes,
            notesCall: PaidCall(model: notesModel, usage: Usage(inputTokens: 152_340, outputTokens: 9_870)),
            verifyCall: verify,
            verification: "ok, 2 flagged"
        )
    }

    @Test func opusCost() {
        let usd = Pricing.usd(model: "claude-opus-5-5", usage: Usage(inputTokens: 152_340, outputTokens: 9_870))
        #expect(String(format: "%.2f", usd ?? -1) == "0.81")
    }

    @Test func haikuBelowTier() {
        let usd = Pricing.usd(model: "claude-haiku-5-5", usage: Usage(inputTokens: 100_000, outputTokens: 2_000))
        #expect(abs((usd ?? -1) - (0.01 + 0.001)) < 1e-9)
    }

    @Test func haikuTierSwitch() {
        let usd = Pricing.usd(model: "claude-haiku-5-5", usage: Usage(inputTokens: 120_000, outputTokens: 2_000))
        #expect(abs((usd ?? -1) - (120_000 * 0.50 / 1e6 + 2_000 * 2.50 / 1e6)) < 1e-9)
    }

    @Test func cacheTokensPriced() {
        let u = Usage(inputTokens: 1_000_000, outputTokens: 0, cacheCreationInputTokens: 1_000_000, cacheReadInputTokens: 1_000_000)
        let opus = Pricing.usd(model: "claude-opus-5-5", usage: u)
        #expect(abs((opus ?? -1) - (4.00 + 5.00 + 0.20)) < 1e-9)
        // Haiku: total 3M > 100k, so input rate 0.50; read 0.05, write 0.625.
        let haiku = Pricing.usd(model: "claude-haiku-5-5", usage: u)
        #expect(abs((haiku ?? -1) - (0.50 + 0.05 + 0.625)) < 1e-9)
        // Cache tokens alone push Haiku over the tier threshold.
        let small = Usage(inputTokens: 50_000, outputTokens: 0, cacheCreationInputTokens: 0, cacheReadInputTokens: 60_000)
        let s = Pricing.usd(model: "claude-haiku-5-5", usage: small)
        #expect(abs((s ?? -1) - (50_000 * 0.50 / 1e6 + 60_000 * 0.05 / 1e6)) < 1e-9)
    }

    @Test func unknownModelNil() {
        #expect(Pricing.usd(model: "gpt-x", usage: Usage()) == nil)
    }

    @Test func headerAfterTitle() {
        let out = header().insert(into: "# T\nbody")
        let lines = out.components(separatedBy: "\n")
        #expect(lines[0] == "# T")
        #expect(lines[2].hasPrefix("> Generated by Faden"))
        #expect(lines.last == "body")
    }

    @Test func headerAtTopWithoutTitle() {
        let out = header().insert(into: "body")
        #expect(out.hasPrefix("> Generated by Faden"))
        #expect(out.hasSuffix("\n\nbody"))
    }

    @Test func markdownLines() {
        let md = header(verify: PaidCall(
            model: "claude-haiku-5-5", usage: Usage(inputTokens: 10, outputTokens: 5, cacheReadInputTokens: 3))).markdown()
        let lines = md.components(separatedBy: "\n")
        #expect(lines[0].hasPrefix("> Generated by Faden on "))
        #expect(lines[0].hasSuffix(" · style A · notes: claude-opus-5-5 · check: claude-haiku-5-5"))
        #expect(lines[1] == "> Sources: slides a.pdf, b.pdf · audio none · my notes none")
        #expect(lines[2] == "> Labels: 📄 slides · 🗣 lecture · 💡 model addition · ✍️ my notes · ⚠️ not found in sources")
        #expect(lines[3] == "> Verification: ok, 2 flagged")
        #expect(lines[4] == "> Cost: $0.81 (152353 in / 9875 out tokens)")
        #expect(lines[5] == "")
        #expect(md.hasSuffix("\n\n"))
    }

    @Test func userNotesNamed() {
        let md = header(userNotes: "mine.md").markdown()
        #expect(md.contains("my notes mine.md"))
    }

    @Test func modelsComeFromTheCalls() {
        let md = header(notesModel: "claude-sonnet-5-5", verify: PaidCall(model: "claude-haiku-5-6", usage: Usage()))
            .markdown()
        #expect(md.components(separatedBy: "\n")[0].hasSuffix(" · notes: claude-sonnet-5-5 · check: claude-haiku-5-6"))
    }

    @Test func checkModelDefaultsWhenVerificationWasSkipped() {
        let first = header().markdown().components(separatedBy: "\n")[0]
        #expect(first.hasSuffix(" · notes: claude-opus-5-5 · check: claude-haiku-5-5"))
    }

    /// An unpriced call must not count as $0.
    @Test func unpricedCallShowsADashAndNamesTheModel() {
        let md = header(verify: PaidCall(model: "mystery-model", usage: Usage(inputTokens: 1, outputTokens: 1))).markdown()
        #expect(md.contains("> Cost: — (price unknown for mystery-model) (152341 in / 9871 out tokens)"))
        let notes = header(notesModel: "other-model").markdown()
        #expect(notes.contains("> Cost: — (price unknown for other-model) (152340 in / 9870 out tokens)"))
    }
}
